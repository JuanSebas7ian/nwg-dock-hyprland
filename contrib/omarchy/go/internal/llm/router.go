// RenderPreset writes llama-server's --models-preset INI: one section per
// model with its effective options. Deterministic (sorted), so an unchanged
// model list gives the same bytes and the router is not restarted for nothing.
func RenderPreset(c Config, models []Model) string {
	var b strings.Builder
	b.WriteString("# Generated by omarchy-llm (contrib/omarchy/go). Edit ~/.config/omarchy-llm/config.json instead.\nversion = 1\n")
	if c.IdleSeconds > 0 {
		fmt.Fprintf(&b, "\n[*]\nsleep-idle-seconds = %d\n", c.IdleSeconds)
	}
	for _, m := range models {
		p := c.Effective(m)
		fmt.Fprintf(&b, "\n[%s]\nmodel = %s\n", m.ID, m.Path)
		if m.MMProj != "" {
			fmt.Fprintf(&b, "mmproj = %s\n", m.MMProj)
		}
		kv := func(k string, v int) {
			if v > 0 {
				fmt.Fprintf(&b, "%s = %d\n", k, v)
			}
		}
		kv("ctx-size", p.Ctx)
		kv("n-gpu-layers", p.GPULayers)
		if p.FlashAttn != "" {
			fmt.Fprintf(&b, "flash-attn = %s\n", p.FlashAttn)
		}
		if p.CacheK != "" {
			fmt.Fprintf(&b, "cache-type-k = %s\n", p.CacheK)
		}
		if p.CacheV != "" {
			fmt.Fprintf(&b, "cache-type-v = %s\n", p.CacheV)
		}
		kv("threads", p.Threads)
		kv("threads-batch", p.ThreadsBatch)
		kv("batch-size", p.Batch)
		kv("ubatch-size", p.UBatch)
		kv("parallel", p.Parallel)
		kv("cache-reuse", p.CacheReuse)
		if p.Jinja != nil {
			if *p.Jinja {
				b.WriteString("jinja = on\n")
			} else {
				b.WriteString("jinja = off\n")
			}
		}
		for _, pair := range strings.Split(p.Extra, ";") {
			if k, v, ok := strings.Cut(pair, "="); ok && strings.TrimSpace(k) != "" {
				fmt.Fprintf(&b, "%s = %s\n", strings.TrimSpace(k), strings.TrimSpace(v))
			}
		}
	}
	return b.String()
}

// RenderEnv is the router service's EnvironmentFile (llama-server reads LLAMA_ARG_*).
func RenderEnv(c Config, presetPath string) string {
	return fmt.Sprintf("OMARCHY_LLM_HOST=%s\nOMARCHY_LLM_PORT=%d\nOMARCHY_LLM_PRESET=%s\nOMARCHY_LLM_MAX=%d\n",
		c.Host, c.Port, presetPath, c.MaxLoaded)
}

// WriteIfChanged writes data atomically and reports whether it changed.
func WriteIfChanged(path, data string, mode os.FileMode) (bool, error) {
	if old, err := os.ReadFile(path); err == nil && string(old) == data {
		return false, nil
	}
	if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
		return false, err
	}
	tmp := path + ".tmp"
	if err := os.WriteFile(tmp, []byte(data), mode); err != nil {
		return false, err
	}
	return true, os.Rename(tmp, path)
}

// RouterModel is one model as the router reports it.
type RouterModel struct {
	ID     string `json:"id"`
	Status string `json:"status"` // loaded | loading | unloaded | sleeping | failed
}

// Router talks to llama-server in router mode.
type Router struct {
	URL  string
	HTTP *http.Client
}

func (r *Router) client() *http.Client {
	if r.HTTP != nil {
		return r.HTTP
	}
	return &http.Client{Timeout: 10 * time.Second}
}

// Up reports whether the router answers.
func (r *Router) Up(ctx context.Context) bool {
	req, _ := http.NewRequestWithContext(ctx, http.MethodGet, r.URL+"/models", nil)
	resp, err := r.client().Do(req)
	if err != nil {
		return false
	}
	resp.Body.Close()
	return resp.StatusCode == http.StatusOK
}

// Models lists the presets and whether each is loaded.
func (r *Router) Models(ctx context.Context) ([]RouterModel, error) {
	req, _ := http.NewRequestWithContext(ctx, http.MethodGet, r.URL+"/models", nil)
	resp, err := r.client().Do(req)
	if err != nil {
		return nil, fmt.Errorf("llama.cpp server is not running: %w", err)
	}
	defer resp.Body.Close()
	var body struct {
		Data []struct {
			ID     string `json:"id"`
			Status struct {
				Value  string `json:"value"`
				Failed bool   `json:"failed"`
			} `json:"status"`
		} `json:"data"`
	}
	if err := json.NewDecoder(resp.Body).Decode(&body); err != nil {
		return nil, fmt.Errorf("llama.cpp server sent an unexpected answer: %w", err)
	}
	out := make([]RouterModel, 0, len(body.Data))
	for _, d := range body.Data {
		st := d.Status.Value
		if d.Status.Failed {
			st = "failed"
		}
		out = append(out, RouterModel{ID: d.ID, Status: st})
	}
	return out, nil
}

func (r *Router) post(ctx context.Context, path, model string) error {
	b, _ := json.Marshal(map[string]string{"model": model})
	req, _ := http.NewRequestWithContext(ctx, http.MethodPost, r.URL+path, bytes.NewReader(b))
	req.Header.Set("Content-Type", "application/json")
	resp, err := r.client().Do(req)
	if err != nil {
		return fmt.Errorf("llama.cpp server is not running: %w", err)
	}
	defer resp.Body.Close()
	if resp.StatusCode >= 300 {
		data, _ := io.ReadAll(io.LimitReader(resp.Body, 4096))
		var e struct {
			Error struct{ Message string } `json:"error"`
		}
		if json.Unmarshal(data, &e) == nil && e.Error.Message != "" {
			return fmt.Errorf("llama.cpp: %s", e.Error.Message)
		}
		return fmt.Errorf("llama.cpp answered %d", resp.StatusCode)
	}
	return nil
}

// Load starts a model and waits until it is ready (or wait passes).
func (r *Router) Load(ctx context.Context, model string, wait time.Duration) error {
	if err := r.post(ctx, "/models/load", model); err != nil && !strings.Contains(err.Error(), "already") {
		return err
	}
	deadline := time.Now().Add(wait)
	for {
		ms, err := r.Models(ctx)
		if err == nil {
			for _, m := range ms {
				if m.ID == model {
					switch m.Status {
					case "loaded":
						return nil
					case "failed":
						return fmt.Errorf("llama.cpp could not load %s (journalctl --user -u llama-router)", model)
					}
				}
			}
		}
		if time.Now().After(deadline) {
			return fmt.Errorf("%s is still loading after %s", model, wait)
		}
		select {
		case <-ctx.Done():
			return ctx.Err()
		case <-time.After(500 * time.Millisecond):
		}
	}
}

// Unload frees a model's memory now.
func (r *Router) Unload(ctx context.Context, model string) error {
	return r.post(ctx, "/models/unload", model)
}

// SyncOpencode writes the "llama" provider of opencode.json with one entry per
// model, keeping every other key, and points the default model at the chosen
// backend. A dated backup is kept the first time each day it changes.
func SyncOpencode(path string, c Config, models []Model, now time.Time) (bool, error) {
	doc := map[string]any{}
	if b, err := os.ReadFile(path); err == nil {
		if err := json.Unmarshal(b, &doc); err != nil {
			return false, fmt.Errorf("%s is not valid JSON, not touching it: %w", path, err)
		}
	}
	if _, ok := doc["$schema"]; !ok {
		doc["$schema"] = "https://opencode.ai/config.json"
	}
	providers, _ := doc["provider"].(map[string]any)
	if providers == nil {
		providers = map[string]any{}
	}
	llama, _ := providers["llama"].(map[string]any)
	if llama == nil {
		llama = map[string]any{}
	}
	llama["npm"] = "@ai-sdk/openai-compatible"
	llama["name"] = "llama.cpp (local)"
	llama["options"] = map[string]any{"baseURL": fmt.Sprintf("http://%s:%d/v1", c.Host, c.Port)}
	entries := map[string]any{}
	for _, m := range models {
		p := c.Effective(m)
		ctxLen := p.Ctx
		if ctxLen == 0 {
			ctxLen = 4096
		}
		label := m.Name
		if m.Quant != "" && !strings.Contains(strings.ToUpper(label), m.Quant) {
			label += " " + m.Quant
		}
		entries[m.ID] = map[string]any{"name": label + " · llama.cpp", "tool_call": true,
			"limit": map[string]any{"context": ctxLen, "output": min(8192, ctxLen/2)}}
	}
	llama["models"] = entries
	providers["llama"] = llama
	doc["provider"] = providers
	if c.DefaultBackend == "llama" && c.DefaultModel != "" {
		doc["model"] = "llama/" + c.DefaultModel
	} else if c.DefaultBackend == "ollama" && c.DefaultModel != "" {
		if s, _ := doc["model"].(string); strings.HasPrefix(s, "llama/") {
			delete(doc, "model")
		}
	}
	b, _ := json.MarshalIndent(doc, "", "  ")
	data := string(b) + "\n"
	if old, err := os.ReadFile(path); err == nil && string(old) != data {
		bak := path + ".bak." + now.Format("20060102")
		if _, err := os.Stat(bak); os.IsNotExist(err) {
			_ = os.WriteFile(bak, old, 0o644)
		}
	}
	return WriteIfChanged(path, data, 0o644)
}
